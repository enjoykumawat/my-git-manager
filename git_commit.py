#!/usr/bin/env python3
"""AI commit message generator — reads staged diff, returns a Conventional Commit."""
import os
import re
import subprocess
import sys

SYSTEM = (
    "You are a git commit message generator. "
    "Output ONLY the commit message — one line, no explanation, no markdown, no quotes, "
    "no co-author lines, no signatures, no AI references. "
    "Follow Conventional Commits: type(scope): subject. "
    "Types: feat, fix, docs, style, refactor, test, chore. "
    "Subject: imperative, lowercase, max 72 chars."
)

# Bare substrings ("llm", "claude", "anthropic") over-matched: any commit
# genuinely about this project's own AI-calling code (e.g. "retry llm calls
# on 429") got erased entirely. These patterns target actual attribution
# signatures instead — see docs/project_notes/bugs.md 2026-07-22 / 2026-07-26.
_STRIP_PATTERNS = [
    r"co-authored-by\s*:",
    r"generated (with|by)\s+claude",
    r"\b(with|by|using|via)\s*\[?\s*claude code\]?",
    r"\bwritten by (an )?(ai|llm|claude|chatgpt|copilot)\b",
    r"\bai-generated\b",
    r"🤖",
    # The system prompt says "no signatures" but the patterns above only ever
    # covered the one trailer spelling ("Co-Authored-By:") this project's own
    # attribution history happened to use — a `Signed-off-by:`, `Reviewed-by:`,
    # `Assisted-by:`, etc. trailer naming an AI, or the bare
    # noreply@anthropic.com address on its own line, sailed straight through
    # this filter untouched. Anchored to the trailer's *value* (not just its
    # label) so a genuinely unrelated commit about a "reviewed-by:" field or
    # a "signed-off-by" DCO bot isn't caught by this. See
    # docs/project_notes/bugs.md 2026-08-12.
    r"\b(signed-off-by|reviewed-by|acked-by|tested-by|reported-by|co-developed-by|assisted-by)\s*:\s*(claude|chatgpt|copilot|anthropic|ai|llm)\b",
    r"noreply@anthropic\.com",
]
_STRIP_RE = re.compile("|".join(_STRIP_PATTERNS), re.IGNORECASE)

# subprocess.check_output with no env= kwarg hands the claude -p child the
# FULL parent environment — including GITHUB_TOKEN (repo+user scope, full
# write) and DEV_TO_API, neither of which this one-shot diff-to-commit-
# message completion has any legitimate use for. --safe-mode (below) only
# drops CLAUDE.md/skills/plugins/hooks/MCP-server auto-discovery — ambient
# environment variables are a separate isolation axis it says nothing
# about. Verified live: a stub "claude" binary invoked with this exact call
# shape (no env=) could read both credentials straight out of its own
# os.environ. See docs/project_notes/bugs.md 2026-08-14.
_CLAUDE_SUBPROCESS_ENV_EXCLUDE = ("GITHUB_TOKEN", "DEV_TO_API")


def _claude_subprocess_env():
    return {k: v for k, v in os.environ.items() if k not in _CLAUDE_SUBPROCESS_ENV_EXCLUDE}


if "--selftest" in sys.argv:
    # Regression cases from the two bugs already logged against this regex:
    # bare-substring over-matching (bugs.md 2026-07-22/26) and the bare
    # `claude code` phrase catching ordinary technical mentions (2026-08-02).
    _CASES = [
        ("co-authored-by: claude <noreply@anthropic.com>", True),
        ("🤖 generated with [claude code](https://claude.ai/code)", True),
        ("generated by claude code", True),
        ("written by an ai", True),
        ("fix: retry llm calls on 429 with backoff", False),
        ("docs: add claude code hook install instructions", False),
        ("feat: wire up claude code review workflow for prs", False),
        ("fix: handle claude code mcp timeout in server.py", False),
        # Trailer/signature spellings the old pattern list never covered —
        # see docs/project_notes/bugs.md 2026-08-12.
        ("Signed-off-by: Claude <noreply@anthropic.com>", True),
        ("Reviewed-by: Claude <noreply@anthropic.com>", True),
        ("Co-Developed-By: Claude", True),
        ("Assisted-by: AI", True),
        ("noreply@anthropic.com", True),
        # Benign vocabulary overlap — must still survive.
        ("docs: add reviewed-by field to PR template generator", False),
        ("feat: signed-off-by trailer support for DCO bot", False),
    ]
    for line, expect_stripped in _CASES:
        got = bool(_STRIP_RE.search(line))
        assert got == expect_stripped, (line, got, expect_stripped)

    # _claude_subprocess_env() must drop GITHUB_TOKEN/DEV_TO_API from what
    # the claude -p child sees, while leaving everything else (PATH, HOME,
    # ...) inherited so claude -p's own OAuth session lookup still works.
    # See docs/project_notes/bugs.md 2026-08-14.
    _saved_gh = os.environ.get("GITHUB_TOKEN")
    _saved_dev = os.environ.get("DEV_TO_API")
    os.environ["GITHUB_TOKEN"] = "selftest-fake-gh-token"
    os.environ["DEV_TO_API"] = "selftest-fake-dev-key"
    try:
        _child_env = _claude_subprocess_env()
        assert "GITHUB_TOKEN" not in _child_env, "GITHUB_TOKEN must not reach the claude -p subprocess"
        assert "DEV_TO_API" not in _child_env, "DEV_TO_API must not reach the claude -p subprocess"
        assert "PATH" in _child_env, "PATH must still be inherited"
    finally:
        if _saved_gh is not None:
            os.environ["GITHUB_TOKEN"] = _saved_gh
        else:
            os.environ.pop("GITHUB_TOKEN", None)
        if _saved_dev is not None:
            os.environ["DEV_TO_API"] = _saved_dev
        else:
            os.environ.pop("DEV_TO_API", None)

    print("selftest ok")
    raise SystemExit(0)

try:
    # The 2026-07-23 fix's own writeup claimed both subprocess calls in this
    # file got a timeout ("neither ... had a timeout ... Fixed both"), but
    # the actual commit (2f9d850) only added timeout= to the claude -p call
    # below. This call — `git diff --staged`, which can hang on a held
    # index.lock or a slow external diff/textconv driver — was left with
    # none, so the "hung process hangs git commit indefinitely" bug the fix
    # claimed to close was still reachable through the call one line above
    # it. See docs/project_notes/bugs.md 2026-08-06.
    diff = subprocess.check_output(["git", "diff", "--staged"], text=True, timeout=20)
except subprocess.TimeoutExpired:
    print("git diff --staged timed out after 20s", file=sys.stderr)
    raise SystemExit(1)
except UnicodeDecodeError as e:
    # text=True decodes git's output with the locale's default encoding
    # (utf-8 here). A staged file containing bytes that aren't valid UTF-8
    # (a cp1252-authored file, a legacy CSV, a stray non-ASCII byte) makes
    # this raise before the diff is even checked for emptiness. Via the
    # prepare-commit-msg hook this crash is invisible: `2>/dev/null` drops
    # the traceback and `&&` short-circuits on the non-zero exit, so the
    # commit just silently gets no AI message — no error shown anywhere.
    print(f"git diff --staged produced non-UTF-8 output: {e}", file=sys.stderr)
    raise SystemExit(1)
if not diff.strip():
    print("Nothing staged. Run `git add` first.")
    raise SystemExit(1)

# claude -p takes the prompt as a single argv element (see below). The OS
# caps total argv+environ size (getconf ARG_MAX; 2 MiB on this machine) —
# a large enough staged diff (a lockfile regen, a big refactor, a vendored
# file) blows past it with a raw, uncaught OSError: none of this script's
# three except clauses below is OSError. Bound it before building the
# argv and fail through this script's own convention instead.
_MAX_DIFF_BYTES = 200_000
if len(diff.encode()) > _MAX_DIFF_BYTES:
    print(
        f"Staged diff is {len(diff.encode())} bytes, over the "
        f"{_MAX_DIFF_BYTES}-byte limit for a claude -p argv. Write your own commit message.",
        file=sys.stderr,
    )
    raise SystemExit(1)

try:
    # --safe-mode disables CLAUDE.md/skills/plugins/hooks/MCP-server
    # auto-discovery while leaving OAuth auth intact (unlike --bare, which
    # forces ANTHROPIC_API_KEY/apiKeyHelper and refuses to read the OAuth
    # session this script actually authenticates with — see key_facts.md
    # "No ANTHROPIC_API_KEY"). Without it, this call inherits whatever
    # CLAUDE.md happens to sit in the caller's cwd — verified live: a bare
    # `claude -p` from this repo's root loads this project's own
    # "MANDATORY routing rules" for a one-line commit-message completion
    # that never calls a tool. See docs/project_notes/bugs.md 2026-08-10.
    raw = subprocess.check_output(
        ["claude", "-p", "--safe-mode", SYSTEM + "\n\n" + diff],
        text=True,
        timeout=20,
        stderr=subprocess.PIPE,
        env=_claude_subprocess_env(),
    ).strip()
except subprocess.TimeoutExpired:
    print("claude -p timed out after 20s", file=sys.stderr)
    raise SystemExit(1)
except subprocess.CalledProcessError as e:
    print(f"claude -p exited {e.returncode}: {(e.stderr or '').strip()[:200]}", file=sys.stderr)
    raise SystemExit(1)
except FileNotFoundError:
    print("claude CLI not found on PATH", file=sys.stderr)
    raise SystemExit(1)

# Safety filter — drop any line that looks like attribution
msg = "\n".join(
    l for l in raw.splitlines()
    if not _STRIP_RE.search(l)
).strip()

print(msg)
